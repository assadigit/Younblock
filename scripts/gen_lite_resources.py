#!/usr/bin/env python3
"""gen_lite_resources.py — the lite desktop edition's exe resources.

Two outputs, both committed (builds stay hermetic — nothing here runs
at build time afterwards):

  assets/lite-app.ico
      The owner's mark (packaging/icons/younblock.png, the 512 px
      source the D108 mipmap set uses) downscaled to the standard
      Windows icon sizes, bundled as an ICO with PNG entries — the
      same writer scripts/gen_icons.py uses.

  cmd/younblock-lite/rsrc_windows_amd64.syso
  cmd/younblock-lite/rsrc_windows_386.syso
      The Win32 resource object (icon + version info) go build links
      into the exe on each matching GOOS/GOARCH; generated by
      goversioninfo (go run @v1.4.1 — a one-shot tool, never a repo
      dependency).

The version strings come from internal/config AppVersion (the one
source of truth), so a version bump regenerates these via this script
— the lockstep note in defaults.go records that.
"""
import json
import os
import re
import struct
import subprocess
import sys
import io

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_PNG = os.path.join(ROOT, "packaging", "icons", "younblock.png")
OUT_ICO = os.path.join(ROOT, "assets", "lite-app.ico")
LITE_DIR = os.path.join(ROOT, "cmd", "younblock-lite")
GOVVERSIONINFO = "github.com/josephspurrier/goversioninfo/cmd/goversioninfo@v1.4.1"

SIZES = (256, 128, 64, 48, 32, 24, 16)


def app_version():
    text = open(os.path.join(ROOT, "internal", "config", "defaults.go")).read()
    m = re.search(r'const AppVersion = "([^"]+)"', text)
    if not m:
        sys.exit("could not read AppVersion from internal/config/defaults.go")
    return m.group(1)


def _png_bytes(img):
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


def write_ico_png_entries(path, images):
    """Bundle per-size RGBA images into an ICO with PNG entries (the
    gen_icons.py writer, verbatim)."""
    with open(path, "wb") as f:
        count = len(images)
        f.write(struct.pack("<HHH", 0, 1, count))
        blobs = [_png_bytes(img) for img in images]
        offset = 6 + 16 * count
        for img, blob in zip(images, blobs):
            w = img.width % 256
            h = img.height % 256
            f.write(struct.pack("<BBBBHHII", w, h, 0, 0, 1, 32, len(blob), offset))
            offset += len(blob)
        for blob in blobs:
            f.write(blob)


def build_ico():
    src = Image.open(SRC_PNG).convert("RGBA")
    write_ico_png_entries(OUT_ICO, [src.resize((s, s), Image.LANCZOS) for s in SIZES])
    print("wrote", OUT_ICO)


def version_tuple(ver):
    parts = ver.split(".")
    nums = [int(p) for p in parts[:3]] + [0] * (3 - min(3, len(parts)))
    return nums[0], nums[1], nums[2]


def build_syso():
    ver = app_version()
    major, minor, patch = version_tuple(ver)
    cfg = {
        "FixedFileInfo": {
            "FileVersion": {"Major": major, "Minor": minor, "Patch": patch, "Build": 0},
            "ProductVersion": {"Major": major, "Minor": minor, "Patch": patch, "Build": 0},
            "FileFlagsMask": "3f",
            "FileFlags": "00",
            "FileOS": "040004",
            "FileType": "01",
            "FileSubType": "00",
        },
        "StringFileInfo": {
            "Comments": "Helps YouTube load in your browser. The lite desktop edition: one file, no dependencies.",
            "CompanyName": "github.com/assadigit",
            "FileDescription": "Younblock Lite",
            "FileVersion": f"{major}.{minor}.{patch}.0",
            "InternalName": "younblock-lite-desktop",
            "LegalCopyright": "",
            "OriginalFilename": "younblock-lite-desktop.exe",
            "ProductName": "Younblock Lite",
            "ProductVersion": ver,
        },
        "VarFileInfo": {
            "Translation": {"LangID": "0409", "CharsetID": "04B0"},
        },
    }
    cfg_path = os.path.join(LITE_DIR, "versioninfo.json")
    with open(cfg_path, "w") as f:
        json.dump(cfg, f, indent=2)
        f.write("\n")
    print("wrote", cfg_path)

    for arch, extra in (("amd64", ["-64"]), ("386", [])):
        out = os.path.join(LITE_DIR, f"rsrc_windows_{arch}.syso")
        cmd = ["go", "run", GOVVERSIONINFO,
               "-icon=" + os.path.relpath(OUT_ICO, ROOT),
               "-o", os.path.relpath(out, ROOT)] + extra + [
            os.path.relpath(cfg_path, ROOT)]
        print("running:", " ".join(cmd))
        subprocess.run(cmd, cwd=ROOT, check=True)
        print("wrote", out)


if __name__ == "__main__":
    build_ico()
    build_syso()
